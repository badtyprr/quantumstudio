"""Recover CSS parity checks from vertices and tile boundaries in the source artwork."""
import collections
import hashlib
import itertools
import json
import math
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

number = r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?"

def endpoints(path):
    # Each SVG segment ends at a vertex. The last coordinate pair of a cubic
    # is its endpoint. Control points and closing commands add no vertices.
    tokens = re.findall(number + "|[MmLlHhVvCcZz]", path)
    x = y = 0.0
    points = []
    i = 0
    while i < len(tokens):
        if tokens[i].isalpha():
            command = tokens[i]
            i += 1
        op = command.upper()
        if op == "Z":
            continue
        n = {"M":2, "L":2, "H":1, "V":1, "C":6}[op]
        args = list(map(float, tokens[i:i+n]))
        i += n
        if op == "H":
            x = args[0] + (x if command.islower() else 0)
        elif op == "V":
            y = args[0] + (y if command.islower() else 0)
        else:
            x = args[-2] + (x if command.islower() else 0)
            y = args[-1] + (y if command.islower() else 0)
        points.append((x,y))
        if op == "M":
            command = "l" if command == "m" else "L"
    return points

def css(qubits, xs, zs):
    def echelon(rows):
        pivots = {}
        for v in rows:
            while v:
                k = v.bit_length()-1
                if k not in pivots:
                    pivots[k] = v
                    break
                v ^= pivots[k]
        return pivots
    assert all((x & z).bit_count() % 2 == 0 for x in xs for z in zs)
    k = qubits-len(echelon(xs))-len(echelon(zs))
    return dict(qubits=qubits, x_rank=len(echelon(xs)), z_rank=len(echelon(zs)), logical=k)

def mask(indices):
    return sum(1 << i for i in set(indices))

def stabilizer_masks(path):
    paths=[e for e in ET.parse(path).iter() if e.tag.endswith("path")]
    style=lambda e:e.get("style","")
    markers=[e for e in paths if "fill:#78a9ff" in style(e) or "fill:#c9ddff" in style(e)]
    grid=collections.Counter(e.get("transform") for e in markers).most_common(1)[0][0]
    centers=set()
    for e in markers:
        if e.get("transform") == grid:
            points=endpoints(e.get("d"))
            centers.add(tuple(round((min(axis)+max(axis))/2,2) for axis in zip(*points)))
    centers=sorted(centers)
    def nearest(point):
        return min(range(len(centers)),key=lambda i:math.dist(point,centers[i]))
    xs,zs=[],[]
    if path.stem == "color-code":
        for e in paths:
            if any("fill:"+c in style(e) for c in ("#8a3ffc","#007d79","#9f1853")):
                corners=endpoints(e.get("d"))
                # Some drawn sides run straight through a marked qubit.
                boundary=[i for i,p in enumerate(centers) if any(
                    abs(math.dist(a,p)+math.dist(p,b)-math.dist(a,b))<0.015
                    for a,b in zip(corners,corners[1:]+corners[:1]))]
                xs.append(mask(boundary))
        zs=xs
    elif path.stem == "Steane-color-code":
        edges=set()
        for e in paths:
            if e.get("transform")==grid and "fill:none" in style(e):
                points=endpoints(e.get("d"))
                edges.add(frozenset((nearest(points[0]),nearest(points[-1]))))
        for vertices in itertools.combinations(range(len(centers)),4):
            if all(sum(i in edge and edge <= set(vertices) for edge in edges)==2 for i in vertices):
                xs.append(mask(vertices))
        zs=xs
    elif path.stem == "rotated-surface-code":
        for e in paths:
            if e.get("transform") != grid or "stroke:#121619" not in style(e):
                continue
            vertices=[nearest(p) for p in endpoints(e.get("d")) if math.dist(p,centers[nearest(p)])<0.04]
            if len(set(vertices)) in (2,4):
                (xs if "fill:#343a3f" in style(e) else zs).append(mask(vertices))
    else:
        # Qubits are edge midpoints. A missing neighbor truncates a boundary check.
        gx=sorted({x for x,y in centers})
        gy=sorted({y for x,y in centers})
        index={(gx.index(x),gy.index(y)):i for i,(x,y) in enumerate(centers)}
        for x in range(len(gx)):
            for y in range(len(gy)):
                if (x,y) in index:continue
                neighbors=[index[v] for v in ((x+1,y),(x-1,y),(x,y+1),(x,y-1)) if v in index]
                if len(neighbors)>=3:
                    (xs if x%2 else zs).append(mask(neighbors))
    return len(centers),xs,zs

def analyze(path):
    qubits,xs,zs=stabilizer_masks(path)
    result=css(qubits,xs,zs)
    assert result["logical"]==1,(path.stem,result)
    if qubits <= 25:
        # Test both X and Z errors against the opposite parity checks,
        # excluding words generated by the same-type stabilizers.
        def span(rows):
            words={0}
            for row in rows:
                words |= {w ^ row for w in words}
            return words
        for checks,stabilizers,key in ((xs,zs,"z_distance"),(zs,xs,"x_distance")):
            trivial=span(stabilizers)
            for weight in range(1,qubits+1):
                errors=(mask(support) for support in itertools.combinations(range(qubits),weight))
                if any(word not in trivial and all((word & row).bit_count()%2==0 for row in checks) for word in errors):
                    result[key]=weight
                    break
        result["distance"]=min(result["x_distance"],result["z_distance"])
        assert (qubits,result["distance"]) in [(7,3),(19,5),(25,5)]
    result["sha256"]=hashlib.sha256(path.read_bytes()).hexdigest()
    return result

if __name__ == "__main__":
    figures=Path(sys.argv[1])
    print(json.dumps({name:analyze(figures/(name+".svg")) for name in
        ("color-code","Steane-color-code","rotated-surface-code","surface-code")},indent=2))
